"""Промпт вердикта. Правила одни на любую поставку. Факты подставляются из кода."""

import json

# Текст не называет папки и номера документов. Новая поставка меняет его,
# только если появился новый вид решения. Числа конкретной поставки сюда не писать.
RULES = """\
Ты разбираешь поставку. Код уже прочитал файлы с текстовым слоем и собрал черновик.
Рядом будут этот черновик и фото страниц. Фото смотри. Файл не верстай.

Черновик — не истина. Сверь его с фото и приведи список к тому, что на фото. Любую строку можно оставить, поправить, выкинуть, разбить на несколько или добавить, если на фото её нет. Число, которого нет ни в черновике, ни на фото, не выдумывай.

Два документа одной поставки с разными числами в одном поле не выбирай: поле не подменяй, расхождение напиши в reason. Это про один и тот же лист, посчитанный дважды. Несколько пакингов с разными номерами, чьи места и вес складываются в итог инвойса, — части одной поставки, не конфликт. Скан не заменяет число, которое на спецификации сходится со своим итогом.

Этот текст один. Его получает обычная модель на понятном бланке и более сильная модель на бланке, который код разобрал криво. У сильной модели нет других правил и нет права выдумывать то, чего нет на фото.

Ответ — один JSON без пояснения вокруг:
{
  "header": {
    "seller": "",
    "buyer": "",
    "contract": "",
    "invoice_no": "",
    "currency": "",
    "notes": ""
  },
  "lots": [
    {
      "index": 0,
      "action": "keep",
      "fields": {},
      "reason": ""
    }
  ],
  "flags": []
}

action только keep, fix, drop, split или add. Какую выбрать, решает фото, не черновик.
keep — строка на фото такая же, fields пустой.
fix — на фото другое значение поля. В fields только ключи из columns, которые надо заменить.
drop — строки на фото нет как товара. Лишняя, пустая, с одним случайным значением, итог, шапка, секция, чужой кусок. Её не оставляй.
split — на фото несколько товарных строк, а в черновике одна. В fields положи "parts": список объектов с теми же ключами. Исходную строку второй раз не оставляй.
add — на фото есть лот, которого в черновике нет. index не ставь. В fields положи строку из columns и только то, что видно на фото.

Когда итог на фото виден, сумма штук, мест, нетто, брутто, объёма и денег по твоему списку сходится с ним, а не с суммой сломанного черновика.

Правила, одинаковые для любого бланка:
- Подпись поля ищет значение рядом: справа или строкой ниже. Слово внутри другого слова подписью не является.
- Роль документа берётся из заголовка внутри, не из имени файла и не из имени листа. В одном файле могут быть две роли, например инвойс и пакинг: это один набор строк, не два. Та же роль может лежать в нескольких файлах. Строки не удваивай. Сколько файлов загрузили, на разбор не влияет. Профиль меняет только то, какие файлы ждут на выходе, не то, как читаются строки. Номер из имени файла не подставляй, если на листе другой номер.
- Язык и валюта любые. Валюта товара та, что у колонки цены. Вторая валюта и курс — пересчёт, не вторая цена и не новый столбец.
- Столбцы только из списка columns. Пустое поле так и остаётся пустым, если его нет ни в данных кода, ни на фото. Новый ключ не добавляй.
- Штуки, места, нетто, брутто, объём и сумма складываются. Цена, артикул, код, описание, страна и номер в итоге пустые. Строка итога — не товар, даже если вместо слова итога в колонке суммы стоит только число, равное сумме строк.
- Артикул, код товара и номер строки — разные вещи. Номер строки товаром не является. Код из 8-10 цифр — это ТН ВЭД, не артикул. Если черновик положил его в артикул, перенеси в код товара. Два разных кода рядом храни оба.
- Одинаковое название при разных количествах — разные лоты. Один артикул много раз — тоже разные лоты, не схлопывай.
- Если у одной строки инвойса или спецификации несколько строк пакинга с тем же артикулом и их штуки в сумме равны этой строке, это несколько лотов. Строка с общей цифрой — не лишний лот. Вес, который на фото один на несколько артикулов, по строкам не дели.
- Если у строки инвойса нет артикула, а в пакинге несколько строк, чьи названия начинаются с того же слова и количества в сумме равны этой строке, это тоже несколько лотов. Пустая клетка описания под уже названной строкой — то же описание. Короткое имя варианта с цифрой — артикул, длинный номер этой строки — модель. Строка, где в колонке мест только число и больше ничего нет, товаром не является.
- EXPORTER — продавец, IMPORTER — покупатель. QUANTITY(MT) и TOTAL QTY (MT) — метры. MT2 — площадь, не метры и не объём.
- Строки одного изделия по контейнерам, у которых количество и сумма стоят один раз, а не в каждой строке, — один лот. Места и вес таких строк складываются. Отдельный лот из части не делай.
- Две одинаковые таблицы рядом на разных языках — один набор строк. Сверь, что количества совпали. Если совпали, второй язык не удваивает лоты.
- Единица может сидеть в шапке колонки, а в клетке быть голое число. package и quantity не смешивай: на пакинге количество часто означает места.
- Скан без текстового слоя код не читает. Числа с такого фото переноси в вердикт только если они на фото реально есть. Не выдумывай вес, код и номер.
- Печать, подпись и логотип данными не являются.
- Имя до слов «именуемый в дальнейшем» или hereinafter — это сторона. Хвост «с одной стороны» именем не является.
- Номер пункта вида 2.1.1 после слова order — не номер заказа.
- Номера размеров во второй строке шапки — сетка одной строки. Число под номером размера — количество этого размера. Это не отдельный лот и не единственный размер в первой клетке.
- Подписи покупателя и продавца в одной строке: имя каждой стороны стоит под своей подписью. Соседняя подпись именем не является.
- Слово invoice внутри шапки колонки не задаёт роль документа, если заголовок листа — спецификация, пакинг или проформа. «the invoice» и «of the invoice» внутри фразы — тоже не заголовок.
- Заголовок документа может стоять ниже названия фирмы и адреса. Роль берётся из него.
- Таблица со стилем, количеством и ценой без колонки описания всё равно товар.
- pairs и пар это одна единица. Разное написание подписи конфликтом не является.
- Seller's и другое притяжательное после слова стороны именем не является. Seller's bank information не продавец.
- Новая строка номеров размеров внутри таблицы сменяет сетку для строк ниже. Те же колонки могут означать другие размеры.
- CBM/CTN, UNIT G.W. и UNIT N.W. относятся к одной коробке. В строку берётся G.W., N.W. и MEASUREMENT.
- Если цвет одного стиля в пакинге другой, а инвойс и спецификация совпали, цвет не заменяй на цвет пакинга.
- Число перед запятой и названием города на строке адреса не номер документа.
- Колонка CODE или KOD — артикул, если это не HS CODE и не таможенный код.
- BOX QTY и количество коробок — места. GOODS PCS — штуки. На одном пакинге могут быть обе колонки.
- TOTAL KG без слова nett — брутто строки. TOTAL NETT — нетто строки. EACH BOX KG — вес одной коробки, не вес строки.
- Строка без названия, у которой штуки или места равны сумме строк выше, — итог, даже если слова TOTAL нет.
- Вторая колонка описания на другом языке дописывается к первой. Слитая ячейка описания относится ко всем строкам, которые она закрывает. Лоты из-за этого не удваиваются.
- Если места одного артикула на инвойсе и в пакинге разные, одно число не выбирай и в fields место не подменяй. Расхождение напиши в reason.
- Строка Origin или Manufacturer под таблицей относится ко всем лотам, у которых это поле пустое. Два разных значения не выбирай.
- Номер с дефисом в одной клетке — один номер. Его части по отдельности не добавляй.
- Колонка таможенного кода поставщика — второй код. Код ТН ВЭД — основной, даже если колонка поставщика стоит левее.
- Строка сбора без артикула и без количества (упаковка, доставка, консолидация) — не товар. Её сумма входит в деньги поставки, в штуки не входит.
- Если спецификация даёт одну строку с артикулом и ценой, а инвойс расписывает её на детали и цены деталей складываются в эту цену, детали не отдельные лоты. Прайс с другими артикулами к этой поставке не клеить.
- Слово EURO перед именем (судно, название) — не валюта евро. Валюта товара та, что у цены.
- Одинаковое число веса на товаре, на строках сборов и в итоге — не сумма строк. Его не складывать.
- Если в колонке единицы стоит число, а в соседней клетке без шапки pcs, шт или set, число — делитель цены, слово — единица.
- Перевод той же подписи на другом языке именем не является. Buyer и следом Покупатель — одна подпись, имя строкой ниже.
- Слово стороны внутри предложения именем не является.
- Если несколько подписей стоят в одной строке, значение каждой — в клетке под ней. Номер спецификации с номером контракта не путай.
- Слово part в колонке мест — не число и не отдельная коробка. В колонке паллет part — общая паллета, эти строки в число паллет не складывай.
- BRUT KG — брутто строки. Колонка ТМ — марка.
- Опечатка BYUER — подпись покупателя.
- Если подпись страны повторена на другом языке в той же строке, значение — названия страны, не текст подписи.
- Если итог packages на скане равен числу паллет, а колонка мест в спецификации сходится со своим итогом, места не заменяй на паллеты.
- Артикул, у которого в числовой клетке пропал нуль в начале, — тот же артикул, что и с нулём. Вторую строку не создавай.
- Если на инвойсе пустые места, нетто или брутто, а в спецификации эти колонки заполнены, бери их из спецификации. Уже заполненное число не затирай.
- «Размер коробки» — габарит упаковки, не размер товара. Отдельного столбца под длину, ширину и высоту нет.
- G.W./CTN и N.W./CTN — вес одной коробки. Если в такой колонке стоит число всей строки, это вес строки, не вес коробки.
- Qty/Ctn и «кол-во в коробке» — штуки в одной коробке, не количество строки.
- Подпись DATE, ADDRESS или CONTRACT сразу после имени стороны в имя не входит.
- «No INVOICE» — номер инвойса, так же как «INVOICE NO». «INVOICE:» и следом номер — тот же номер.
- Вторая колонка артикула — модель или заводской код рядом с первым артикулом, не второй лот.
- Несколько документов одной роли относятся к поставке, если совпали контракт, номер или артикулы. Такие строки не удваивай: пустые поля допиши, уже заполненное число не затирай. Таблица с другими артикулами — чужой файл, её строки и валюту в лоты не переноси.
- CTNS, коробка и места — количество мест. N.W./CTN, G.W./CTN и размер коробки местами не являются.
- YUAN — та же валюта, что CNY. Короткий цвет вроде BLK и более полное black / чёрный — один цвет, в лот берётся более полное.
- Колонка Specifications — текст товара, не роль документа и не второй лот.

Аналогии, когда явной подписи нет, а место на бланке узнаваемое. Число, которого нет на фото, от этого не появляется. Если кандидатов два и они разные, не выбирай.
- Фирма в шапке бланка, со своим адресом и налоговым номером, до слов To, Bill to, Sold to или Messrs — продавец, даже без слова Seller. Фирма, на которую документ адресован этими словами, — покупатель.
- From, Shipper и блок отправителя над своим адресом — продавец. To, Bill to, Sold to — покупатель. Beneficiary у банка — счёт, не имя продавца.
- Номер сразу после Invoice, Facture, Rechnung, Счет и двоеточия — номер документа, даже если рядом нет слова No.
- Колонка коротких кодов рядом с длинным текстом — артикул, даже если шапка Item, Code, Art или без слова артикул. Колонка целиком из 8-10 цифр рядом — таможенный код, не артикул.
- Колонка, чьи числа на цену дают сумму строки, — количество. Соседняя, где стоит цена за единицу, — цена. Колонка, равная этому произведению, — сумма.
- Два веса в одной строке без подписи: меньший обычно нетто, больший брутто, и только если итог это подтверждает. Иначе поле не заполняй.
- Строка внизу, чьи числа равны сумме колонок выше, — итог, даже без слова Total.
- Фирма после Manufactured, Made by или Producer — производитель.
- M2, MT2 и sqm — площадь. Это не метры длины и не объём. Если в списке columns есть area, площадь клади туда. Если количество продано в этих единицах, единица берётся из шапки, число не пересчитывается.
- Шапка из нескольких подписей через слэш делит значение строки в том же порядке. Design Name в таком списке — артикул, код цвета рядом — цвет, PO — заказ.
- MANUFACTURER / BRAND в одной колонке делится так же: до слэша производитель, после слэша марка. MODEL / ART. без слэша в клетке — одно число, оно и модель, и артикул, не второй лот.
- Колонка, в шапке которой только перечень единиц (pcs, pcg, set), — единица. Какая именно, стоит в клетке. Несколько слов шапки само по себе не конфликт.
- Слово колонки, разорванное пробелом перед последней буквой, читается слитно, если слитно это известная подпись. Количество мест от этого не пропадает.
- Вторая колонка нетто with primary packaging или «с первичной упаковкой» — не замена первого нетто и не брутто. Если в columns есть net_primary, клади туда. Первое нетто не затирай.
- Буква в номере контракта берётся как напечатана. Похожая буква другого алфавита на латинскую не заменяется.
- Bill to и Sold to — покупатель. Колонка Customer Name, если в клетке короткое имя товара с цифрой, — артикул, не покупатель.
- Количество рулонов — места. Метры в соседней колонке — количество. Таблица без нарисованных линий всё равно таблица: колонки стоят друг под другом.
- Строка без номера в колонке No, у которой рулоны, метры и площадь равны сумме нумерованных дизайнов над ней и у которой стоит цена, — не отдельный лот. Цена переходит на эти дизайны. Сумма каждого равна его метрам на эту цену. Общий вес этой строки на один дизайн не переносить.
- Строки рулонов с тем же именем, что дизайн, чьи метры в сумме равны строке дизайна, — детализация этого дизайна, не отдельные лоты. Нетто и брутто дизайна — сумма рулонов, если она сходится с весом группы в пакинге. Не сходится — поле не заполняй и напиши расхождение в reason.
- Список длин в одной клетке, сумма которого равна количеству этой строки, — метры отдельных рулонов той же строки, не новые лоты. Строку не разбивай.
- METERS и TOTAL METERS — количество, единица из колонки единицы. WIDTH — ширина, клади в width, если такой ключ есть в columns. G/M — граммы на метр, клади в gsm, если ключ есть. Это не вес строки и не места.
- INV.NO. — номер инвойса, так же как INVOICE NO. EX-WORK и EXW в начале строки — условие поставки. Дата после DATE, записанная названием месяца, — дата документа. Фирма над заголовком COMMERCIAL INVOICE или PACKING LIST — продавец, даже без слова Seller.
"""


def build_prompt(result):
    """Правила плюс то, что код уже собрал. Словарь результата не меняется."""
    payload = {
        "documents": result.get("documents") or [],
        "columns": list(result.get("columns") or []),
        "header": {
            "seller": result.get("seller") or "",
            "buyer": result.get("buyer") or "",
            "contract": result.get("contract") or "",
            "invoice_no": result.get("invoice_no") or "",
            "invoice_nos": list(result.get("invoice_nos") or []),
            "proforma_no": result.get("proforma_no") or "",
            "proforma_nos": list(result.get("proforma_nos") or []),
            "order_no": result.get("order_no") or "",
            "order_nos": list(result.get("order_nos") or []),
            "currency": result.get("currency") or "",
            "currencies": list(result.get("currencies") or []),
            "invoice_date": result.get("invoice_date") or "",
            "contract_date": result.get("contract_date") or "",
            "delivery": result.get("delivery") or "",
            "container": result.get("container") or "",
            "director": result.get("director") or "",
            "seller_address": result.get("seller_address") or "",
            "buyer_address": result.get("buyer_address") or "",
        },
        "flags": list(result.get("flags") or []),
        "lots": result.get("lots") or [],
    }
    data = json.dumps(payload, ensure_ascii=False, indent=2)
    return RULES + "\nДАННЫЕ КОДА:\n" + data + "\n"


_GOODS_MARKS = ("pieces", "packages", "amount", "price", "vendor", "description")
_SKIP_KEYS = {"index", "action", "reason", "freight", "unit_conflict", "packages_conflict"}


def needs_stronger_model(result, verdict_lots):
    """Код не увидел товар, а вердикт заполнил не больше трёх столбцов. Тогда нужен второй проход."""
    if _code_saw_goods(result):
        return False
    rows = list(verdict_lots or [])
    if not rows:
        return True
    return max(_filled_columns(row) for row in rows) <= 3


def _code_saw_goods(result):
    for lot in (result or {}).get("lots") or []:
        if lot.get("freight"):
            continue
        if any(lot.get(name) not in (None, "", [], {}) for name in _GOODS_MARKS):
            return True
    return False


def _filled_columns(row):
    fields = row.get("fields") if isinstance(row, dict) and isinstance(row.get("fields"), dict) else row
    count = 0
    for key, value in (fields or {}).items():
        if key in _SKIP_KEYS:
            continue
        if value not in (None, "", [], {}):
            count += 1
    return count
