_GOODS_MARKS = ("pieces", "packages", "amount", "price", "vendor", "description")
_SKIP_KEYS = {
    "index",
    "action",
    "reason",
    "freight",
    "unit_conflict",
    "packages_conflict",
    "conflicts",
    "weight_suspect",
    "hs_alt_shipper",
}


def needs_stronger_model(result, verdict_lots):
    """Код не увидел товар, а вердикт заполнил не больше трёх столбцов. Тогда нужен второй проход.

    packages_gap и weight_conflict тоже зовут сильную модель: слитые места и два пакинга
    с разными итогами обычный проход часто оставляет keep.
    """
    flags = set((result or {}).get("flags") or [])
    if flags & {"packages_gap", "weight_conflict"}:
        return True
    if _code_saw_goods(result):
        return False
    rows = list(verdict_lots or [])
    if not rows:
        return True
    return max(_filled_columns(row) for row in rows) <= 3


def _code_saw_goods(result):
    for lot in (result or {}).get("lots") or []:
        if lot.get("freight"):
            continue
        if any(lot.get(name) not in (None, "", [], {}) for name in _GOODS_MARKS):
            return True
    return False


def _filled_columns(row):
    fields = row.get("fields") if isinstance(row, dict) and isinstance(row.get("fields"), dict) else row
    count = 0
    for key, value in (fields or {}).items():
        if key in _SKIP_KEYS:
            continue
        if value not in (None, "", [], {}):
            count += 1
    return count
